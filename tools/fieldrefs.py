# ---------------------------------------------------------------------------
# Il2CppTypeEnum -> (width, is_reference). Only the cases that can appear as a
# field type. Anything absent is answered UNKNOWN (0, ...) and refused, never
# guessed.
# ---------------------------------------------------------------------------
PRIM = {
    0x02: (1, 0),   # BOOLEAN
    0x03: (2, 0),   # CHAR
    0x04: (1, 0),   # I1
    0x05: (1, 0),   # U1
    0x06: (2, 0),   # I2
    0x07: (2, 0),   # U2
    0x08: (4, 0),   # I4
    0x09: (4, 0),   # U4
    0x0a: (8, 0),   # I8
    0x0b: (8, 0),   # U8
    0x0c: (4, 0),   # R4
    0x0d: (8, 0),   # R8
    0x18: (8, 0),   # I   (IntPtr)
    0x19: (8, 0),   # U   (UIntPtr)
}
REF = {
    0x0e: 8,        # STRING
    0x0f: 8,        # PTR
    0x12: 8,        # CLASS
    0x13: 8,        # VAR
    0x14: 8,        # ARRAY
    0x15: 8,        # GENERICINST -- see note in type_info()
    0x1c: 8,        # OBJECT
    0x1d: 8,        # SZARRAY
    0x1e: 8,        # MVAR
}
TE_VALUETYPE = 0x11


def type_byte(R, tidx):
    """The Il2CppTypeEnum of the Il2CppType at index `tidx`.

    Il2CppType is `{ union data; unsigned attrs:16, type:8, num_mods:6,
    byref:1, pinned:1 }`. `Resolver.field_attrs` already masks 0xFFFF out of
    the u32 at +8; the type byte is the next 8 bits of that same word."""
    tva = R.rq(R.TYPES_PTR + tidx * 8)
    import struct
    w = struct.unpack_from("<I", R.b, R.v2f(tva) + 8)[0]
    return (w >> 16) & 0xFF


def _decl_rows(R, tname):
    t = R.find_one(tname)
    return t, R.all_fields_ex(t)


def valuetype_size(R, tidx, depth=0):
    """Size of a VALUETYPE field, from its own declared instance fields.

    A GENERICINST valuetype has an all-zero fieldOffsets array (the
    GENERIC-NO-LAYOUT case) and is answered 0 = UNKNOWN, never 0 = empty."""
    if depth > 3:
        return 0
    tva = R.rq(R.TYPES_PTR + tidx * 8)
    import struct
    td = struct.unpack_from("<q", R.b, R.v2f(tva))[0]
    # For a VALUETYPE the `data` union holds the typeDefinitionIndex.
    if td < 0 or td >= R.NTYPES:
        return 0
    try:
        rows = R.declared_fields_ex(td)
    except Exception:
        return 0
    if not rows:
        return 0
    end = 0
    for r in rows:
        if r["static"] or not r["has_storage"]:
            continue
        if r["layout"] == "generic" or r["off"] is None:
            return 0
        w, _ref, _lbl = _width_of(R, r["fidx"], depth + 1)
        if w == 0:
            return 0
        end = max(end, r["off"] + w)
    # MEASURED on this build: a VALUE TYPE's own fieldOffsets entries are
    # OBJECT-HEADER-RELATIVE, not struct-relative -- UnityEngine.Color reports
    # r/g/b/a at 0x10/0x14/0x18/0x1c and UnityEngine.Vector2 reports x/y at
    # 0x10/0x14 (`python tools/fldoff.py fields UnityEngine.Color`). The struct
    # is therefore `end - sizeof(Il2CppObject)`; without this subtraction Color
    # comes back 32 bytes, i.e. DOUBLE, which as a store width would run 16
    # bytes past the field. Anything that does not clear the header is answered
    # UNKNOWN rather than a negative or a guess.
    if end <= 0x10:
        return 0
    return end - 0x10


def _fidx_typeindex(R, fidx):
    import struct
    _ni, ti = struct.unpack_from("<ii", R.m, R.FLD_OFF + fidx * 12)
    return ti


def _width_of(R, fidx, depth=0):
    """-> (width, is_reference, kind_label). width 0 means UNKNOWN."""
    ti = _fidx_typeindex(R, fidx)
    tb = type_byte(R, ti)
    if tb in REF:
        # GENERICINST is a reference ONLY when the open definition is a class.
        # We do not have a cheap offline answer for that, so a GENERICINST
        # field is emitted UNKNOWN rather than assumed. No manifest row needs
        # one today; if one does, measure it and add an explicit override.
        if tb == 0x15:
            return (0, 0, "genericinst(UNKNOWN)")
        return (REF[tb], 1, "reference")
    if tb in PRIM:
        w, r = PRIM[tb]
        return (w, r, "primitive")
    if tb == TE_VALUETYPE:
        return (valuetype_size(R, ti, depth), 0, "valuetype")
    return (0, 0, "unknown(0x%02x)" % tb)


def inst_size_min(R, rows):
    """max(off + width) over every INSTANCE field of the type and its bases.

    A LOWER BOUND on Il2CppClass.instance_size -- see the module docstring for
    exactly how weak that is. A field whose width is unknown is SKIPPED, which
    can only make the bound smaller, i.e. refuse more."""
    end = 0
    for r in rows:
        if r["static"] or not r["has_storage"] or r["off"] is None:
            continue
        if r["layout"] == "generic":
            continue
        w, _ref, _k = _width_of(R, r["fidx"])
        if w == 0:
            continue
        end = max(end, r["off"] + w)
    return end


def fieldref_self_check(R):
    """The second self-check, on THIS tool's own additions.

    `fldoff.self_check` proves the OFFSET scan. It says nothing about the
    width/is_reference decoder added here, which is where a silent lie would
    now live. So re-derive three rows whose answers are known independently:

        System.String._stringLength  0x10  width 4  reference 0
        System.String._firstChar     0x14  width 2  reference 0
        UnityEngine.UI.Toggle.m_Group 0x110 width 8 reference 1

    The last one is the falsifier that matters: if `type_byte` were wrong, a
    CLASS field would decode as a primitive and M4 (no narrow store into a
    reference slot) would silently stop applying to every reference in the
    table."""
    want = [("System.String", "_stringLength", 0x10, 4, 0),
            ("System.String", "_firstChar", 0x14, 2, 0),
            ("UnityEngine.UI.Toggle", "m_Group", 0x110, 8, 1)]
    bad = []
    for tname, fname, off, wid, ref in want:
        try:
            _t, rows = _decl_rows(R, tname)
            r = [x for x in rows if x["name"] == fname and not x["static"]][0]
            gw, gref, _k = _width_of(R, r["fidx"])
            got = (r["off"], gw, gref)
        except Exception as e:                       # noqa: BLE001
            got = ("error", str(e), "")
        if got != (off, wid, ref):
            bad.append((tname + "." + fname, got, (off, wid, ref)))
    if bad:
        print("FIELDREF SELF-CHECK FAILED: the width/is_reference decoder does "
              "not reproduce known rows -- refusing to emit any FieldRef.")
        for lbl, got, exp in bad:
            print("   %-34s got=%r exp=%r" % (lbl, got, exp))
        sys.exit(1)


def build(R):
    """-> list of dicts, one per manifest row. Raises SystemExit on any row
    that cannot be resolved to a real offset -- a header with a hole in it is
    worse than no header."""
    out = []
    for sym, tname, fname, note in MANIFEST:
        t, rows = _decl_rows(R, tname)
        hit = [r for r in rows if r["name"] == fname]
        if not hit:
            sys.exit("FIELDREFS FAILED: %s.%s does not exist on this build "
                     "(searched the full parent chain of %s)" %
                     (tname, fname, tname))
        r = hit[0]
        if r["static"]:
            sys.exit("FIELDREFS FAILED: %s.%s is STATIC -- it is not an "
                     "instance field and has no receiver-relative offset" %
                     (tname, fname))
        if not r["has_storage"]:
            sys.exit("FIELDREFS FAILED: %s.%s is a LITERAL (C# const): it has "
                     "no storage, and 0x0 is not its offset" % (tname, fname))
        if r["layout"] == "generic":
            sys.exit("FIELDREFS FAILED: %s is an UNINSTANTIATED GENERIC "
                     "definition; IL2CPP writes an all-zero fieldOffsets array "
                     "for it, so every offset it reports is fabricated" % tname)
        if r["off"] is None:
            sys.exit("FIELDREFS FAILED: %s.%s has no fieldOffsets entry" %
                     (tname, fname))
        w, isref, kind = _width_of(R, r["fidx"])
        if w == 0:
            sys.exit("FIELDREFS FAILED: %s.%s has type %r whose width is not "
                     "derivable offline (%s) -- refusing to guess it" %
                     (tname, fname, r["typename"], kind))
        ns, nm = R.tname(t)
        full = (ns + "." + nm) if ns else nm
        out.append({
            "sym": sym, "type": full, "field": fname, "off": r["off"],
            "width": w, "isref": isref, "instmin": inst_size_min(R, rows),
            "typename": r["typename"], "kind": kind,
            "declared_by": r.get("declared_by", full), "note": note,
        })
    return out


HDR = """/* abi/aowlspt_fieldrefs.h -- GENERATED by tools/fieldrefs.py. DO NOT EDIT.
 *
 * Regenerate:  python tools/fieldrefs.py emit
 * Verify:      python tools/fieldrefs.py check     (exit 5 = drift)
 *
 * Every row was produced by tools/il2cpp_resolve.py's fieldOffsets scan, AFTER
 * tools/fldoff.py:self_check re-derived System.String._stringLength@0x10 and
 * _firstChar@0x14 from the same resolver. No offset in this file was typed by
 * a human.
 *
 * `inst_size_min` is max(offset+width) over the type's instance fields and its
 * bases -- a LOWER BOUND on Il2CppClass.instance_size, which the metadata does
 * not carry. It is the fail-closed direction, and it is weak by construction
 * for the offsets in this very file. The load-bearing checks are the
 * reference-width rule (M4) and klass admission; see aowlspt_hostwrite.h.
 *
 * `klass` / `nklass` are the runtime KLASS ADMISSION SET, filled in by
 * aowl_fr_admit() from receivers the caller vouches for. Zero admitted klasses
 * means every store through this FieldRef is REFUSED.
 */
#ifndef AOWLSPT_FIELDREFS_H
#define AOWLSPT_FIELDREFS_H

#include <stdint.h>

#define AOWL_FR_MAX_KLASS 4

typedef struct AowlFieldRef {
    const char* type_name;      /* metadata type that DECLARES the field      */
    const char* field_name;
    int32_t     off;            /* receiver-relative, from fieldOffsets       */
    int32_t     width;          /* bytes; 0 is impossible here (generator     */
                                /* refuses a width it cannot derive)          */
    int32_t     is_reference;   /* 1 => a managed reference slot (M4 applies) */
    uint32_t    inst_size_min;  /* see the note above                         */
    void*       klass[AOWL_FR_MAX_KLASS];
    int32_t     nklass;
} AowlFieldRef;

"""

FTR = """
#endif /* AOWLSPT_FIELDREFS_H */
"""


def emit(refs, build_id=""):
    b = [HDR]
    if build_id:
        b.append("/* source: %s */\n\n" % build_id)
    for r in refs:
        b.append("/* %s\n"
                 " *   %s.%s : %s   (%s, declared by %s)\n"
                 " */\n" % (r["note"], r["type"], r["field"], r["typename"],
                            r["kind"], r["declared_by"]))
        b.append("static AowlFieldRef AOWL_FR_%s = {\n"
                 "    \"%s\", \"%s\", 0x%x, %d, %d, 0x%x, { 0, 0, 0, 0 }, 0\n"
                 "};\n\n" % (r["sym"], r["type"], r["field"], r["off"],
                             r["width"], r["isref"], r["instmin"]))
    # One accessor per row. Nim binds THESE, never the objects: `importc` on a
    # proc emits a CALL, so `(&AOWL_FR_X)` as a proc name compiles to
    # `(&AOWL_FR_X)()` -- "called object is not a function or function
    # pointer". Going through a real function also keeps `AowlFieldRef`'s
    # layout entirely on the C side, so Nim cannot be made to disagree with it.
    b.append("\n")
    for r in refs:
        b.append("static AowlFieldRef* aowl_fr_%s(void) { return &AOWL_FR_%s; }\n"
                 % (r["sym"].lower(), r["sym"]))
    b.append("\n")
    # The whole table, for the inspector's ADVISORY lookup. Nothing writes
    # through this array: it exists so a deliberately RAW write can be TOLD
    # what the metadata thinks of the address it is about to touch.
    b.append("static AowlFieldRef* AOWL_FR_ALL[] = {\n")
    for r in refs:
        b.append("    &AOWL_FR_%s,\n" % r["sym"])
    b.append("};\n")
    b.append("#define AOWL_FR_TABLE_ROWS %d\n" % len(refs))
    b.append(FTR)
    return "".join(b)


