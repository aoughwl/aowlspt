#!/usr/bin/env python3
"""fieldrefs.py -- generate `abi/aowlspt_fieldrefs.h` from the IL2CPP metadata.

WHY THIS EXISTS
===============
`docs/WRITE-AUDIT-2026-09-02.md` section 5 and `docs/INTERACTION-LAYER-MAP.md`
M3/M6: every host/mod store into game-owned memory today is handed a BARE
OFFSET, and its only guard is readability -- a test that CANNOT FAIL on the
IL2CPP GC heap, because the pages stay mapped after an object dies.

A bare offset also cannot answer the one question that produced the
`0x00000000FFFFFFFF` crash: *is this slot a REFERENCE?* A 4-byte store of -1
into a reference slot whose upper dword was already zero is producer (A) in
that audit, and nothing in the tree could refuse it.

So the offset stops being an integer literal in Nim and becomes a generated
descriptor:

    (type_name, field_name) -> (offset, width, is_reference, inst_size_min)

emitted as C, consumed by `abi/aowlspt_hostwrite.h`'s `aowl_fr_store_*`.
"Is 0x110 on this object an int or a ToggleGroup?" becomes a build artifact
instead of a comment.

THE SELF-CHECK IS MANDATORY (CLAUDE.md section 5)
=================================================
`tools/fldoff.py:self_check` re-derives `System.String._stringLength@0x10` and
`_firstChar@0x14` before anything is printed. This tool calls the SAME function
and additionally re-derives it as a FieldRef row, so the generated header is
never written from a resolver that failed its own sanity check. Failure prints
only the failure, writes nothing, and exits non-zero.

WHAT `inst_size_min` IS, AND WHAT IT IS NOT
==========================================
The metadata does NOT carry `Il2CppClass.instance_size`; that is built at
runtime. What is derivable offline is `max(offset + width)` over every INSTANCE
field of the type and its bases -- a LOWER BOUND on the real instance size.

That is the fail-closed direction (it can only refuse writes the real size
would have allowed, never allow one it would have refused), and it is stated
here rather than dressed up: for a FieldRef generated by this tool the bound
check is **weak by construction**, because the offset came out of the same
table. It is non-vacuous only against a hand-edited or stale header. The checks
that carry real weight are the REFERENCE-WIDTH rule and the klass-admission
rule; see `abi/aowlspt_hostwrite.h`.

VALUE-TYPE WIDTHS
=================
A primitive's width comes from its `Il2CppTypeEnum`. A VALUETYPE's (Color,
Vector2, an enum) is computed by recursing into ITS declared instance fields
and taking the same max(off+width), capped in depth. Measured on this build:
`UnityEngine.Color` -> 16 (four floats reported at 0x10/0x14/0x18/0x1c,
because a value type's fieldOffsets are OBJECT-HEADER-relative; the header is
subtracted, see `valuetype_size`). A width that cannot
be derived is emitted as 0, and `aowl_fr_store_*` REFUSES a FieldRef of width 0
rather than guessing.

USAGE
=====
    python tools/fieldrefs.py [GAMEASM] [METADEC] emit [--out abi/aowlspt_fieldrefs.h]
    python tools/fieldrefs.py [GAMEASM] [METADEC] print
    python tools/fieldrefs.py [GAMEASM] [METADEC] check   # regenerate + diff, exit 5 on drift

Exit codes: 0 ok, 1 self-check or resolve failure, 5 `check` found drift.
"""

