def parse_mod_config(path):
    """Pull (key, value, doc) out of a mod config.json.

    These files carry their own documentation in sibling keys -- either
    `_keyComment` / `_key` or `//key` -- immediately beside the key they
    describe. That convention is what makes this page generable at all.
    """
    try:
        raw = json.loads(read(path))
    except Exception as e:
        return None, str(e)
    if not isinstance(raw, dict):
        return None, "top level is not an object"

    docs, keys = {}, []
    for k, v in raw.items():
        if k.startswith("//") or k.startswith("_"):
            target = k.lstrip("/_")
            for suffix in ("Comment", ""):
                if suffix and target.endswith(suffix):
                    target = target[: -len(suffix)]
                    break
            if target and isinstance(v, str):
                # `_comment` / `//` are file-level, not key-level.
                if target.lower() in ("comment", ""):
                    docs.setdefault("__file__", []).append(v)
                else:
                    docs[target] = v
            continue
        keys.append((k, v))
    return {"keys": keys, "docs": docs}, None


def collect_mods():
    moddir = os.path.join(ROOT, "mods")
    out = []
    for n in sorted(os.listdir(moddir)):
        d = os.path.join(moddir, n)
        if not os.path.isdir(d):
            continue
        cfgpath = os.path.join(d, "config.json")
        cfg, err = (None, "no config.json")
        if os.path.exists(cfgpath):
            cfg, err = parse_mod_config(cfgpath)
        readme = os.path.join(d, "README.md")
        out.append({
            "name": n,
            "dir": rel(d),
            "config": cfg,
            "config_error": err,
            "config_path": rel(cfgpath) if os.path.exists(cfgpath) else None,
            "has_readme": os.path.exists(readme),
            "sources": sorted(
                f for f in os.listdir(d) if f.endswith(".nim")),
        })
    return out


def page_mods_index(mods):
    out = [GENERATED_BANNER, "# Mods\n"]
    out.append(
        "The %d mods under `mods/`. Each is a nimony library built against the host\n"
        "ABI, shipping a `config.json` whose keys are its settings surface.\n"
        % len(mods))
    documented = sum(1 for m in mods if m["config"])
    total_keys = sum(len(m["config"]["keys"]) for m in mods if m["config"])
    out.append(
        "%d of %d carry a parseable `config.json`, %d settings keys between them.\n"
        % (documented, len(mods), total_keys))
    out.append("| Mod | Settings keys | Sources | README |")
    out.append("| --- | --- | --- | --- |")
    for m in mods:
        nk = len(m["config"]["keys"]) if m["config"] else 0
        cell = str(nk) if m["config"] else "_none_"
        out.append("| [`%s`](./mods/%s) | %s | %s | %s |" % (
            m["name"], m["name"], cell,
            ", ".join("`%s`" % s for s in m["sources"]) or "_UNKNOWN_",
            "yes" if m["has_readme"] else "no"))
    return "\n".join(out) + "\n"


def page_mod(m):
    out = [GENERATED_BANNER, "# `%s`\n" % m["name"]]
    out.append("Source: [`%s`](https://github.com/aoughwl/aowlspt/blob/main/%s).\n"
               % (m["dir"], m["dir"]))
    if not m["config"]:
        out.append("## Settings\n\n_UNKNOWN — %s._\n" % m["config_error"])
        return "\n".join(out) + "\n"

    filedoc = m["config"]["docs"].get("__file__", [])
    if filedoc:
        out.append("## What it does\n")
        for d in filedoc:
            out.append("> %s\n" % md_safe(d).replace("\n", "\n> "))

    out.append("## Settings\n")
    out.append("Defined in [`%s`](https://github.com/aoughwl/aowlspt/blob/main/%s). "
               "The values shown are the **shipped defaults**, not what is currently "
               "deployed.\n" % (m["config_path"], m["config_path"]))
    for k, v in m["config"]["keys"]:
        out.append("### `%s`\n" % k)
        out.append("- **Default:** `%s`" % json.dumps(v))
        doc = m["config"]["docs"].get(k)
        if doc:
            out.append("\n%s\n" % md_safe(doc))
        else:
            out.append("\n_UNKNOWN — this key carries no doc comment in "
                       "`config.json`._\n")
        # Some configs document individual VALUES of a key with dotted doc keys
        # -- `//preset.filmic` beside `//preset`. That is real documentation and
        # dropping it silently would be exactly the kind of quiet loss this
        # generator exists to prevent.
        subs = sorted((dk, dv) for dk, dv in m["config"]["docs"].items()
                      if isinstance(dk, str) and dk.startswith(k + "."))
        if subs:
            out.append("\nAccepted values:\n")
            for dk, dv in subs:
                out.append("- **`%s`** — %s" % (dk[len(k) + 1:], md_safe(dv)))
            out.append("")
    return "\n".join(out) + "\n"


