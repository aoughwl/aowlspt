#
# WHY THE TYPE OVERLOAD AND NOT THE STRING ONE. MEASURED 2026-09-02, build
# 1.1.0.1.46777: `Component::GetComponent(String)` matches through a runtime
# type-name lookup that does not resolve on this IL2CPP build. A walk of ALL
# 1263 nodes of an OPEN Settings screen -- a screen made of captions -- found
# ZERO `TextMeshProUGUI` components, while the inspector's `label` reads their
# text fine. A predicate that cannot say yes makes every absence verdict vacuous
# (CLAUDE.md 9b), and this mod's map selection is entirely a text comparison, so
# it would have been vacuous in exactly the place it matters most.
#
# The Type overload matches by KLASS IDENTITY inside the runtime, which is the
# question actually being asked, and -- unlike `GetComponents(Type)`, which
# returns an array -- it ALLOCATES NOTHING, so it is legal on a per-node path.
#
# Getting a `System.Type` without reflection: `System.Type::GetTypeFromHandle`
# takes a `RuntimeTypeHandle`, a one-field struct whose value IS the
# `Il2CppType*`, so on Win64 it is a plain pointer in RCX. The address of the
# static `Il2CppType` for a named type is resolved OFFLINE out of
# `Il2CppMetadataRegistration.types`. These eight were read on 2026-09-04 with
#
#   python tools/il2cpp_nameindex.py lookup \
#       D:\Aowlspt\aowlspt\aowlspt-names.idx "<Ns.Type>::@type" 0
#
# against the index whose stamp matches this build. They are DATA RVAs, so
# there is no prologue to verify -- which is stated plainly rather than glossed:
# the checks available are the image bound, readability, and the fact that the
# address is never called, only handed to a byte-verified method whose ANSWER is
# then re-checked. `typeObject` below returns nil, with a reason, on any of
# those failing.
# ---------------------------------------------------------------------------

