  ## `Toggle::Set(value, sendCallback)` -- THE GAME'S OWN WAY to turn a toggle
  ## on. `sendCallback = true` at every call site here on purpose: the point of
  ## pressing the control is to run the handler the screen attached to it.
  result = false
