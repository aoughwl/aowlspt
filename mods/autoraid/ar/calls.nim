proc unityEventInvoke*(ev: Il2CppPtr; why: var string): bool =
  ## `UnityEvent::Invoke()` -- the WEAKER path, used only as an announced
  ## fallback when a DefaultUIButton's own `_button` is unreachable. It reaches
  ## the same handler but SKIPS the button's interactable gate, and MEASURED
  ## 2026-09-02 that left the profile/mode screen half-transitioned with neither
  ## card clickable. Every caller says out loud that it took this route.
  ##
  ## The guard before it is a FLOOR, not proof: a managed object's first qword
  ## is its `Il2CppClass*`, so an object that is really there has a readable
  ## klass pointer whose own first pointer is readable too. That rejects a value
  ## which is not a live managed object at all -- the class of value that faults
  ## -- and it cannot certify that `ev` IS a UnityEvent. Saying which of those
  ## it is doing is the whole point of the sentence.
  result = false
  why = ""
  if ev == nil:
    why = "the OnClick UnityEvent slot read null"
    return
  if not readable(ev, 0x40):
    why = "the event pointer is not readable for 0x40 bytes, so it is not a " &
          "live managed object. Nothing was called."
    return
  let klass = readPtr(ev, 0)
  if klass == nil or not readable(klass, 0x40):
    why = "the object in the OnClick slot has no readable Il2CppClass* in its " &
          "first qword, so it is not a live managed object. Nothing was called."
    return
  var a = callArgs()
  addPtr(a, ev)
  let o = callVoid(tUnityEventInvoke, a)
  if o.kind != coOk:
    why = o.why
    return
  result = true

