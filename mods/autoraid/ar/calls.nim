## ar/calls.nim -- EVERY CALL THIS MOD MAKES INTO THE GAME, AND NOTHING ELSE.
##
## One file, one reason: a call into IL2CPP is the operation with the highest
## cost of being wrong in this whole project, and the only way to keep the
## discipline visible is to keep every instance of it in one place where the
## rules can be read off the page.
##
## THE RULES THIS FILE OBEYS, AND HOW EACH IS ENFORCED RATHER THAN INTENDED
## ------------------------------------------------------------------------
## * **Never by name.** Fact #145: resolving an IL2CPP name is harmless and
##   USING one is fatal -- `CameraManager::get_Instance` by name, `Physics::
##   Raycast` bound by name and `AddActivePLayer` patched by name each killed
##   the client instantly and silently. Nothing here resolves a name. Every
##   target is an RVA plus the sixteen bytes it is DECLARED to begin with.
## * **Byte-verify before the first call.** `aowlspt/callrva` compares the
##   declared prologue against a CAPTURE-ONCE snapshot of the original bytes,
##   and refuses -- by name, with a sentence -- on a mismatch, on an RVA outside
##   the image, on an RVA outside the `il2cpp` section (generated code lives
##   there, NOT in `.text`). A first byte that is a JUMP means somebody
##   detoured the function before we looked -- almost always the HOST's own
##   uihooks/nativetabs hooks (MEASURED 2026-09-05: `Toggle::Set`,
##   `SettingsScreen::Close`, `MenuScreen::ShowInRaid`, and the raid entry
##   stopped at SIDE while they were refused). Calling THROUGH a hook is
##   correct, so `callrva` then asks the host for its pre-detour snapshot
##   (`aowlspt.host::original_bytes`) and byte-verifies against THAT; a host
##   with no row for the RVA, or a mismatch, is still a refusal by name.
## * **Never DETOUR a shared RVA.** This file detours nothing at all, so the
##   hazard has no surface here. `owners` is still carried from the generated
##   table and printed, because "1 owner" said out loud is worth more than an
##   assumption left unstated. CALLING a shared RVA is correct: it is correct
##   code for the receiver passed.
## * **One guard, never nested.** Each call is wrapped by callrva's own vectored
##   guard, and that guard REFUSES TO ARM inside another (`GUARD_BUSY`), on its
##   own flag and on the shim's. So this mod opens no outer guard anywhere --
##   see the header of `ar/native.nim` for why that is the shape rule 3 takes
##   here.
## * **Three outcomes, never two.** Every wrapper below returns the value AND an
##   `ok`, or nil-with-a-reason. "The call faulted" and "the call returned zero"
##   are different answers and nothing here flattens them.
##
## WHERE THE RVAs AND THE PROLOGUES COME FROM
## ------------------------------------------
## Two sources, and the difference matters:
##
##   * `abi/aowlspt_symtab.nim` -- GENERATED by `tools/il2cpp_symtab.py` from
##     `abi/aowlspt_symbols.txt`. A symbol that is ambiguous or shared is
##     REJECTED by the generator and is then simply ABSENT from that file, so
##     referencing it is a compile error rather than a run-time surprise. Every
##     target that can come from there does.
##   * a hand-declared RVA + the sixteen bytes pasted from the `abi/` header
##     that measured them. Used only where the generated table has no row: the
##     manifest names an overload as `Type::Method/arity` and cannot
##     disambiguate by PARAMETER TYPE, so e.g. `Toggle::Set(bool,bool)` has no
##     key. Each such target names the header and the date the bytes came from.
##
## The build identity both rest on is `AowlSymtabImageKey` /
## `AowlSymtabFileSha256`, logged once at load, so a run against a different
## `GameAssembly.dll` is visible in the log rather than inferred from a pile of
## refusals.

