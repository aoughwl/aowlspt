var gInstalled = false

proc hexOf(bs: openArray[uint8]): string =
  ## The generated table carries BYTES; `rvaTarget` declares a HEX STRING. One
  ## conversion here beats sixteen hand-typed bytes per target, and a hand-typed
  ## prologue is precisely what the generator exists to stop anyone writing.
  const digits = "0123456789abcdef"
  result = ""
  var i = 0
  while i < bs.len:
    if i > 0: result.add ' '
    result.add digits[int(bs[i] shr 4'u8)]
    result.add digits[int(bs[i] and 0x0F'u8)]
    inc i

