# ---------------------------------------------------------------------------
# Verification, ONCE, at load. Reading the code page is safe at mod init: it
# neither patches nor calls, and a target that refuses here refuses loudly with
# the reason instead of at the first press with a plausible silence.
# ---------------------------------------------------------------------------

type
  CallsState* = object
    tried*: bool
    ok*: int         ## targets that byte-verified
    bad*: int        ## targets that REFUSED, each already logged by name
    faults*: int     ## guarded calls that took an access violation
    disabled*: bool  ## the whole call surface is off for this session
    why*: string     ## the first refusal, for the one-line verdict

var gS: CallsState

const MaxCallFaults* = 8
  ## Rule 6, as a WHOLE-FILE budget rather than one per target. A wrong calling
  ## convention would not fault on only one channel, so a per-target budget
  ## would let the same underlying mistake spend eight lives instead of one.

proc note(t: var RvaTarget) =
  let v = verify(t)
  if v.kind == coOk:
    gS.ok = gS.ok + 1
    debug "AutoRaid: " & v.why
  else:
    gS.bad = gS.bad + 1
    if gS.why.len == 0: gS.why = v.why
    warn "AutoRaid: " & v.why & " -- this target is REFUSED for the whole " &
         "session and NOTHING will be called through it."

proc verifyAll*(): CallsState =
  ## Byte-verify every target. Idempotent. Returns the finished state, which is
  ## what the caller reports -- never "we called verify", which is not a fact
  ## about the client.
  if gS.tried: return gS
  gS.tried = true
  installTargets()
  note tChildCount
  note tGetChild
  note tActiveInHierarchy
  note tGetName
  note tCompGameObject
  note tCompTransform
  note tGetRoot
  note tUnityEventInvoke
  note tButtonPress
  note tTypeFromHandle
  note tGetComponentType
  note tToggleSet
  note tPointerClick
  note tSettingsClose
  note tShowInRaid
  note tMenuShowCtrl
  result = gS

proc callsDisabled*(): bool =
  ## The kill switch, read at the top of every tick. It trips on the SHARED
  ## fault counter callrva maintains process-wide, not on a counter of our own:
  ## a mod that invents its own would be measuring something else.
  if gS.disabled: return true
  if int(faultCount()) - gS.faults >= MaxCallFaults:
    gS.disabled = true
    warn "AutoRaid: SELF-DISABLED -- " & $MaxCallFaults & " guarded calls " &
         "into the game have faulted this session. Every feature of this mod " &
         "that touches the client is OFF for the rest of the run; the menu " &
         "and the settings still work and nothing further will be called."
    return true
  result = false

proc noteFaultBase*() =
  ## Record the process-wide fault count at arming time, so this mod's budget
  ## counts ITS OWN faults rather than inheriting another mod's.
  gS.faults = int(faultCount())

proc buildIdentity*(): string =
  ## The build every RVA in this file was measured against. Logged once at load
  ## so that a run on a different `GameAssembly.dll` is a visible statement in
  ## the log rather than something inferred from a pile of refusals.
  "imageKey 0x" & $AowlSymtabImageKey & ", GameAssembly.dll sha256 " &
  AowlSymtabFileSha256

# ---------------------------------------------------------------------------
# The wrappers. Each is the ONLY way this mod performs that operation.
# ---------------------------------------------------------------------------

#
# THE RECEIVER GATE, applied by every one of them and stated once here: a
# receiver must be READABLE and ALIVE. Readable is not alive -- a destroyed
# Unity object stays readable with `m_CachedPtr` zeroed (fact #182), and a
# managed call on that corpse faults inside Unity, which is the single most
# common way this mod could kill the client. The gate is repeated in each
# wrapper rather than factored into a "checked call" helper because the helper
# would have to be generic over slot shapes, and a generic call path is the one
# thing `callrva` deliberately refuses to be.

proc receiverOk(p: Il2CppPtr): bool =
  (not callsDisabled()) and readable(p, 0x20) and alive(p)

proc childCount*(tr: Il2CppPtr; ok: var bool): int =
  ## `Transform::get_childCount`. `ok` distinguishes "no children" from "could
  ## not look", which a bare 0 cannot -- and a walk that treats the second as
  ## the first reports an empty screen and calls it an answer.
  ok = false
  result = 0
  if not receiverOk(tr): return
  var a = callArgs()
  addPtr(a, tr)
  let o = callInt(tChildCount, a)
  if o.kind != coOk: return
  ok = true
  result = int(o.g)

proc childAt*(tr: Il2CppPtr; i, n: int): Il2CppPtr =
  ## `Transform::GetChild(index)`. THE INDEX IS BOUNDS-CHECKED HERE, against the
  ## `n` the caller just read, because `GetChild` THROWS on an out-of-range
  ## index and a managed exception thrown through a native frame is not
  ## something this mod can survive. `n` is passed in rather than re-read so
  ## that the bound and the loop cannot drift apart.
  result = nil
  if i < 0 or i >= n: return
  if not receiverOk(tr): return
  var a = callArgs()
  addPtr(a, tr)
  addInt(a, int64(i))
  let o = callPtr(tGetChild, a)
  if o.kind != coOk: return
  let c = asPtr(o)
  if c != nil and readable(c, 0x20): result = c

proc gameObjectOf*(comp: Il2CppPtr): Il2CppPtr =
  ## `Component::get_gameObject`. A Transform IS a Component, so this is the
  ## legal way from a walked node to the object `activeInHierarchy` is declared
  ## on. Going the other way -- calling a Component method with a GameObject in
  ## RCX -- is fact #68 and faults inside Unity.
  result = nil
  if not receiverOk(comp): return
  var a = callArgs()
  addPtr(a, comp)
  let o = callPtr(tCompGameObject, a)
  if o.kind != coOk: return
  let g = asPtr(o)
  if g != nil and readable(g, 0x20): result = g

proc transformOf*(comp: Il2CppPtr): Il2CppPtr =
  ## `Component::get_transform`. How a SCREEN RECEIVER -- which arrives as the
  ## screen's MonoBehaviour, not as a Transform -- becomes something the walkers
  ## can descend. Note this RVA has 15 owners; that is fine to CALL (it is
  ## correct code for the receiver passed) and would be catastrophic to detour,
  ## which this mod never does.
  result = nil
  if not receiverOk(comp): return
  var a = callArgs()
  addPtr(a, comp)
  let o = callPtr(tCompTransform, a)
  if o.kind != coOk: return
  let t = asPtr(o)
  if t != nil and readable(t, 0x20): result = t

proc rootOf*(tr: Il2CppPtr): Il2CppPtr =
  ## `Transform::get_root` -- THE ONE WAY THIS MOD REACHES A SCENE ROOT.
  ##
  ## The host walks `DontDestroyOnLoad`'s roots via `GameObject::
  ## get_scene_Injected` + `Scene::GetRootGameObjects`. This mod deliberately
  ## does not: `GetRootGameObjects` ALLOCATES (a List and an array), which is
  ## banned on a per-frame path, and MEASURED 2026-09-02 the enumeration is the
  ## LOCATION scene once a raid has loaded, so it cannot see the menu at all.
  ##
  ## Climbing from a receiver the game handed us is strictly better and is the
  ## repo's own rule: reach a container by WALKING from a verified live object,
  ## never by an enumeration that can legitimately be empty. `Common UI` is the
  ## root of the MenuScreen receiver; `Menu UI` is the root of the matchmaker
  ## screens. Both are therefore reachable in one call from something the game
  ## proved was alive.
  result = nil
  if not receiverOk(tr): return
  var a = callArgs()
  addPtr(a, tr)
  let o = callPtr(tGetRoot, a)
  if o.kind != coOk: return
  let r = asPtr(o)
  if r != nil and readable(r, 0x20): result = r

proc nodeName*(node: Il2CppPtr): string =
  ## `Object::get_name`, decoded by the fixed `System.String` layout. "" means
  ## NOT READABLE or genuinely empty; no caller may treat "" as a match.
  result = ""
