proc activeInHierarchy*(node: Il2CppPtr; ok: var bool): bool =
  ## `GameObject::get_activeInHierarchy`, reached through `get_gameObject`.
  ##
  ## `ok` is the whole point. An INACTIVE control is NOT PRESSABLE (fact #72):
  ## pressing one returns success and does nothing. "Could not look" must never
  ## collapse into either answer, because "not active" makes the mod wait
  ## forever and "active" makes it press a corpse.
  ok = false
  result = false
  let go = gameObjectOf(node)
  if go == nil: return
  var a = callArgs()
  addPtr(a, go)
  let o = callBool(tActiveInHierarchy, a)
  if o.kind != coOk: return
  ok = true
  result = o.g != 0'i64

proc isActive*(node: Il2CppPtr): bool =
  ## The two-valued form, for the many places that want "definitely active".
  ## Deliberately FALSE when the read failed: a walk must not press something it
  ## could not confirm is on screen.
  var ok = false
  let a = activeInHierarchy(node, ok)
  result = ok and a

# ---- components -----------------------------------------------------------

proc typeObject*(typeRva: uint32; why: var string): Il2CppPtr =
  ## `System.Type::GetTypeFromHandle(Il2CppType*)`. No reflection anywhere in
  ## this chain: the handle is a static DATA address resolved offline, and the
  ## method is byte-verified like every other.
  ##
  ## Re-derived on every call rather than cached across frames: the runtime
  ## returns its OWN cached Type object, so this is a lookup and not an
  ## allocation, and re-deriving means a search that spans frames never carries
  ## a stale managed pointer across a GC.
  result = nil
  why = ""
  if callsDisabled():
    why = "the call surface is self-disabled for this session"
    return
  let td = dataAt(typeRva)
  if td == nil:
    why = "the offline Il2CppType address 0x" & $typeRva & " is not readable " &
          "here -- either GameAssembly.dll is not mapped yet, or this is not " &
          "the build those addresses were measured against"
    return
  var a = callArgs()
  addPtr(a, td)
  let o = callPtr(tTypeFromHandle, a)
  if o.kind != coOk:
    why = "System.Type::GetTypeFromHandle " & o.why
    return
  let t = asPtr(o)
  if t == nil or not readable(t, 0x20):
    why = "GetTypeFromHandle returned something that is not a usable " &
          "System.Type, so no component lookup was attempted"
    return
  result = t

proc componentOf*(node: Il2CppPtr; typeRva: uint32; why: var string): Il2CppPtr =
  ## `Component::GetComponent(Type)` on a Transform receiver.
  ##
  ## A NULL RETURN IS AN ANSWER, not a failure: it means this object has no
  ## component of that type. `why` distinguishes that from "nothing was called",
  ## and both call sites in this mod care about the difference.
  result = nil
  why = ""
  if not receiverOk(node):
    why = "the receiver is not readable, or its native half is null " &
          "(a destroyed object stays readable -- fact #182)"
    return
  let tobj = typeObject(typeRva, why)
  if tobj == nil: return
  var a = callArgs()
  addPtr(a, node)
  addPtr(a, tobj)
  let o = callPtr(tGetComponentType, a)
  if o.kind != coOk:
    why = "Component::GetComponent(Type) " & o.why
    return
  let c = asPtr(o)
  if c == nil:
    why = "GetComponent(Type) returned NULL -- an ANSWER: this object carries " &
          "no component of that type"
    return
  if not readable(c, 0x20):
    why = "GetComponent(Type) returned a pointer that is not readable"
    return
  result = c

# ---- the three press routes ----------------------------------------------
#
# THREE KLASSES, THREE ROUTES, EACH MEASURED. There is deliberately NO generic
# route, because the generic route is what faulted: `arOnClickOff` in the host
# returned the generic UnityEvent offset 0x100 for every klass that was not a
# DefaultUIButton, and on an `EFT.UI.AnimatedToggle` that offset is
# `toggleTransition` -- an ENUM. A small integer is not null, is not a
# GameObject and is not a known klass, so it passes every guard available, and
# is then CALLED as a UnityEvent. Two deterministic access violations.

