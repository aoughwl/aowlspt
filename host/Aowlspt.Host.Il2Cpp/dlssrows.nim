proc dlrChoiceMap(r: DlrRow): string =
  ## "  (1 = DLSS / 2 = FSR 3.1 / 3 = XeSS)" -- the caption suffix a CHOICE row
  ## needs when it is built as a stepper slider instead of a dropdown, derived
  ## from the catalogue's own `choices` so the two can never disagree.
  result = ""
  if r.choices.len == 0: return
  var acc = "  ("
  var i = 0
  while i < r.choices.len and i < 16:
    if i > 0: acc = acc & " / "
    acc = acc & $(i + 1) & " = " & r.choices[i]
    i = i + 1
  acc & ")"

proc dlrNoteFault(what: string) =
  inc gDlrFaults
  warn "dlss rows: " & what & " (fault " & $gDlrFaults & " of " &
       $DlrMaxFaults & ")"
  if gDlrFaults >= DlrMaxFaults:
    gDlrOff = true
    warn "dlss rows: self-disabled for this session after " & $gDlrFaults &
         " fault(s). No row of ours is left in the Graphics page."

proc dlrDestroyAll(): int =
  ## Tear down every row WE made. The game never will: they are deliberately
  ## not in `SettingsTab._createdControls` (that list is an instantiated
  ## generic whose layout is not reachable offline, and a raw write into one is
  ## a fabricated offset into a collection the game then iterates).
  result = 0
  var i = 0
  while i < gDlrRowGo.len and i < DlrMaxRows:
    let go = gDlrRowGo[i]
    if go != nil and duOk(go, 0x20'i32) and iUnityAlive(go):
      if nuDestroy(go): result = result + 1
    i = i + 1
  gDlrRowGo = @[]
  gDlrRowKey = @[]
  gDlrRowT = @[]
  gDlrRowCtrl = @[]
  gDlrRowTip = @[]
  gDlrTipWant = @[]
  gDlrRowDdb = @[]
  gDlrRowChoices = @[]
  gDlrDropWanted = 0
  gDlrDropBuilt = 0
  gDlrDropWhy = ""
  gDlrTipAsked = 0
  gDlrTipCalled = 0
  gDlrTipVerified = 0
  gDlrTipWhy = ""
  gDlrPlaced = -1
  gDlrPlaceWhy = ""
  gDlrBuilt = false
  gDlrBuiltN = 0
  gDlrSeeded = 0
  gDlrRefused = 0

proc dlrTab(): Il2CppPtr =
  ## The live `GraphicsSettingsTab` COMPONENT, by WALKING from the validated
  ## "Graphics Settings" panel transform. `modsComponent` refuses a GameObject
  ## receiver up front, which is the fault this walk would otherwise take.
  result = nil
  if gGfxPanelT == nil or not duOk(gGfxPanelT, 0x20'i32): return
  if not iUnityAlive(gGfxPanelT): return
  result = modsComponent(gGfxPanelT, "GraphicsSettingsTab")
  if result != nil and not nuOk(result, DlrOffFloatSliderTmpl + 8'i32):
    result = nil

proc dlrMakeRow(prefab, parent: Il2CppPtr; r: DlrRow; asDropdown: bool;
                sliderOut, ctrlOut, ddbOut: var Il2CppPtr): Il2CppPtr =
  ## ONE row, the game's own way. No `SetSiblingIndex` is called: `Instantiate`
  ## appends, which puts our section AFTER the stock rows -- and any index we
  ## chose would REORDER controls the game created, which is a write to stock
  ## state this file does not make.
  result = nil
  sliderOut = nil
  ctrlOut = nil
  ddbOut = nil
  let row = nuInstantiateUnder(prefab, parent)
  if row == nil: return
  let go = nuGameObjectOf(row)
  if go == nil:
    warn "dlss rows: the instantiated row for '" & r.key & "' has no " &
         "reachable GameObject, so it could be neither shown nor torn down. " &
         "Refusing this row."
    return
  # `SetText` takes a LOCALIZATION KEY; an aowlspt setting has no BSG locale
  # entry, so the literal renders as itself. A raw `m_text` store would be
  # clobbered by `LocalizedText`, which is why the setter is called.
  let caption = (if r.kind == dlrDropdown and not asDropdown:
                   r.label & dlrChoiceMap(r) else: r.label)
  if not nuRowSetText(row, caption):
    warn "dlss rows: SetText refused for '" & r.key & "'; the row would carry " &
         "the PREFAB's own caption, which reads as a stock setting that is " &
         "not there. Refusing this row."
    discard nuDestroy(go)
    return
  discard nuRowSetName(row, "aowlspt-dlss-" & r.key)
  if asDropdown:
    # A CLONED `SettingDropDown`. The widget is reached through
    # `SettingDropDown.DropDown` @0xA8 and filled by CALLING the game's own
    # `Show` -- see `nuDropDownShow`, which refuses unless the receiver's own
    # vtable slot 24 resolves to one of three byte-verified bodies AND the
    # String[] it built really carries `IEnumerable<string>` in the interface
    # table `Show` dispatches against.
    let ddb = nuDropDownOf(row)
    if ddb == nil:
      gDlrDropWhy = "SettingDropDown.DropDown @0xA8 read null or unreadable " &
                    "on the cloned row, so there is no DropDownBox to fill"
      discard nuDestroy(go)
      return
    var why = ""
    if not nuDropDownShow(ddb, r.choices, why):
      gDlrDropWhy = why
      discard nuDestroy(go)
      return
    ddbOut = ddb
  elif r.kind == dlrSlider or r.kind == dlrDropdown:
    let sl = nuRowSlider(row)
    if sl == nil:
      warn "dlss rows: '" & r.key & "' instantiated but its inner NumberSlider " &
           "(SettingFloatSlider.Slider @0xa8) read null, so the row would show " &
           "a slider with no range and no value. Refusing it."
      discard nuDestroy(go)
      return
    if not nuSliderShow(sl, r.lo, r.hi, r.fmt):
      warn "dlss rows: NumberSlider::Show refused for '" & r.key & "' (range " &
           nuF(r.lo) & ".." & nuF(r.hi) & "). Refusing this row."
      discard nuDestroy(go)
      return
    discard nuSliderSetValue(sl, r.def)
    sliderOut = sl
  discard nuSetActive(go, true)
  ctrlOut = row
  result = go

## ---------------------------------------------------------------------------
## PLACEMENT -- our section sits DIRECTLY AFTER the stock DLSS pair
##
## `Instantiate` appends, so without this the five rows land at the BOTTOM of
## the Graphics page, far from the two stock rows they belong with
## ("Setting14: NvidiaDlss" and "Setting15: DlssPreset"). Order inside the row
## container is the container's LayoutGroup's business and sibling index is how
## the game itself orders its own rows, so it is the only ordering that
## survives a relayout.
##
## THE ANCHOR IS FOUND BY NAME, ON THE LIVE CONTAINER, EVERY BUILD -- never by
## a remembered index. "Setting15" is a POSITION in BSG's own list: a patch
## that adds one graphics setting renumbers it, and an index we cached would
## then insert our block in the middle of an unrelated stock section while
## every call still succeeded. The name that carries meaning is `DlssPreset`,
## so that is the substring matched, and the numeric prefix is not required.
##
## THE VERDICT IS A READBACK THROUGH `Transform::GetSiblingIndex`, which is a
## different function from the one that wrote it (both named in the nativeui
## positional self-check for exactly that reason). It can FAIL: if the write
## did not take, or Unity clamped it, the index read back differs from the one
## asked for and the count says so.
const DlrMaxScanChildren = 128
const DlrAnchorName = "DlssPreset"

proc dlrFindAnchor(parent: Il2CppPtr; outIdx: var int32; why: var string): bool =
  ## The sibling index of the stock `Setting15: DlssPreset` row under
  ## `parent`, by walking the container's children and reading each
  ## GameObject's own name. Bounded by `DlrMaxScanChildren` and every hop
  ## validated: a corrupt `childCount` inside a frame is an infinite loop on
  ## the Unity main thread.
  result = false
  outIdx = -1'i32
  why = ""
  var n = 0
  if not iChildCount(parent, n):
    why = "the row container did not answer childCount"
    return
  if n <= 0 or n > DlrMaxScanChildren:
    why = "the row container reported " & $n & " child(ren), which is outside " &
          "the 1.." & $DlrMaxScanChildren & " range this walk accepts"
    return
  var i = 0
  var seen = 0
  while i < n and i < DlrMaxScanChildren:
    let c = iChildAt(parent, i)
    if c != nil and duOk(c, 0x20'i32) and iUnityAlive(c):
      seen = seen + 1
      let nm = iObjName(c)
      if nm.len > 0 and modsNameHas(nm, DlrAnchorName):
        outIdx = int32(i)
        return true
    i = i + 1
  why = "no child of the row container has a name containing '" &
        DlrAnchorName & "' (" & $seen & " of " & $n & " children were live " &
        "and named). The stock DLSS pair is not on this page on this build"
  false

proc dlrPlaceRows(parent: Il2CppPtr) =
  ## Move every row of ours to sit immediately after the anchor, in catalogue
  ## order, and READ BACK where each one landed.
  ##
  ## The moves go in ascending order for a reason: our rows start at the END of
  ## the container, so moving the first to `anchor+1` shifts everything between
  ## `anchor+1` and its old slot up by one -- the anchor itself does not move,
  ## because it sits BELOW the insertion point. Re-reading the anchor between
  ## moves would therefore be wrong as often as it was right.
  gDlrPlaced = -1
  gDlrPlaceWhy = ""
  if gDlrRowT.len == 0:
    gDlrPlaceWhy = "no row transform was captured, so nothing could be moved"
    return
  var anchorIdx = -1'i32
  var why = ""
  if not dlrFindAnchor(parent, anchorIdx, why):
    gDlrPlaceWhy = why
    return
  var ok = 0
  var k = 0
  while k < gDlrRowT.len and k < DlrMaxRows:
    let t = gDlrRowT[k]
    let want = anchorIdx + 1'i32 + int32(k)
    if t != nil and duOk(t, 0x20'i32) and iUnityAlive(t) and
       nuSetSiblingIndex(t, want):
      let (readOk, got) = nuSiblingIndex(t)
      if readOk and got == want: ok = ok + 1
    k = k + 1
  gDlrPlaced = ok

## ---------------------------------------------------------------------------
## TOOLTIPS -- the game's own hover tooltip, on our rows
##
## `SettingControl::SetTooltip(SettingsTooltipData, SettingsTooltip)` @0x16FAC00
## (UNIQUE, non-virtual, section `il2cpp`) does NOT keep the object it is
## handed: MEASURED `disasm 0x16fac00 --len 940`, it builds its own through
## `SettingsTooltipData::.ctor(ESettingsOption)` @0x16FCD70, copies the fields
## across (`mov rax,[rbp+0x20]` -> `mov [rdi+0x20],rax` is Text), and stores
## the hover area into `_tooltipSettingsHover@0x98`. It has THREE no-op paths
## -- `_blocker@0x88` null, `UiElementBlocker::TryGetTooltip` false, and a null
## data argument -- and NO throw path.
##
## So what we build is a TEMPLATE, and `true` from the call proves nothing.
## The verdict re-reads `_tooltipSettingsHover@0x98 -> _tooltipData@0x20 ->
## Text@0x20` off each row and requires the POINTER to be the exact interned
## string that was handed over, which is a property of the finished state and
## is falsifiable by every one of the three no-op paths.
const DlrMaxTipScan = 128

proc dlrDonorTooltipData(parent: Il2CppPtr): Il2CppPtr =
  ## A LIVE `SettingsTooltipData`, borrowed from the stock DlssPreset row, so
  ## that `il2cpp_object_new` gets a class pointer that came off an object the
  ## GAME made rather than out of any metadata lookup. Walked, never offset-ed
  ## into from nowhere: container child (matched on the same name the placement
  ## anchor uses) -> its `SettingDropDown` component -> `_tooltipSettingsHover`
  ## @0x98 -> `_tooltipData` @0x20.
  result = nil
  var n = 0
  if not iChildCount(parent, n): return
  if n <= 0 or n > DlrMaxTipScan: return
  var i = 0
  while i < n and i < DlrMaxTipScan:
    let c = iChildAt(parent, i)
    if c != nil and duOk(c, 0x20'i32) and iUnityAlive(c):
      let nm = iObjName(c)
      if nm.len > 0 and modsNameHas(nm, DlrAnchorName):
        let ctrl = modsComponent(c, "SettingDropDown")
        if ctrl != nil:
          let d = nuTooltipDataOf(ctrl)
          if d != nil: return d
        return
    i = i + 1

proc dlrMakeTooltipData(title, body: string; why: var string): Il2CppPtr =
  ## ONE `SettingsTooltipData` TEMPLATE for a DLSS row.
  ##
  ## The body of this proc MOVED to `nativeui.nim` as `nuMakeTooltipData` on
  ## 2026-09-04, unchanged, so that `postfxrows.nim` gets this exact mechanism
  ## rather than a second copy of it that could drift. The two row files are
  ## `include`d in the order postfx-then-dlss and cannot see each other;
  ## nativeui is `include`d before both. Nothing about the DLSS behaviour
  ## changes: the same donor klass, the same `frAdmit` gate, the same six
  ## typed stores, the same named refusals.
  nuMakeTooltipData(gDlrTipKlass, "dlssrows.tooltip", title, body, why)

proc dlrApplyTooltips(parent: Il2CppPtr) =
  ## Attach a tooltip to every row of ours that declares one, then VERIFY by
  ## reading the finished state back. Runs ONCE per build; nothing here is on a
  ## per-frame path and nothing here allocates after it has run.
  if not gDlrTipsOn or gDlrRowCtrl.len == 0: return
  gDlrTipKlass = nil
  let donor = dlrDonorTooltipData(parent)
  if donor == nil:
    gDlrTipWhy = "no live SettingsTooltipData could be borrowed from the " &
                 "stock '" & DlrAnchorName & "' row (no child of the row " &
                 "container carries that name, it has no SettingDropDown " &
                 "component, or its _tooltipSettingsHover@0x98 / " &
                 "_tooltipData@0x20 read null). Without a donor there is no " &
                 "class pointer to allocate against, and none is invented"
    return
  gDlrTipKlass = nuKlassOf(donor)
  if gDlrTipKlass == nil:
    gDlrTipWhy = "the donor SettingsTooltipData's object header did not read " &
                 "back a class pointer"
    return
  var i = 0
  while i < gDlrRowCtrl.len and i < DlrMaxRows:
    if gDlrRowTip[i].len > 0 and gDlrRowCtrl[i] != nil:
      gDlrTipAsked = gDlrTipAsked + 1
      var wb = ""
      var wd = ""
      let body = nuStrWhy(gDlrRowTip[i], wb)
      let data = dlrMakeTooltipData(gDlrRowKey[i], gDlrRowTip[i], wd)
      if data != nil and body != nil:
        gDlrTipWant[i] = body
        if nuSetTooltip(gDlrRowCtrl[i], data):
          gDlrTipCalled = gDlrTipCalled + 1
        else:
          warn "dlss rows: tooltip '" & gDlrRowKey[i] & "' -- the template " &
               "was BUILT and SetTooltip was refused before it was made (the " &
               "control did not validate, or the @0x16FAC00 prologue did not " &
               "verify). Nothing was called for this row."
      else:
        # ONE LINE PER FAILING ROW, naming the row AND the cause. The previous
        # version recorded only the FIRST failure into a shared string, so four
        # rows failing for one reason read as one row failing for another.
        warn "dlss rows: tooltip '" & gDlrRowKey[i] & "' NOT applied -- " &
             (if data == nil: wd else: "the body string: " & wb) & "."
        if gDlrTipWhy.len == 0:
          gDlrTipWhy = "first failure was '" & gDlrRowKey[i] & "': " &
                       (if data == nil: wd else: wb)
    i = i + 1
  # THE VERDICT, and it is a property of the FINISHED STATE: the tooltip the
  # control now carries must be the string we handed over. Reading back what we
  # wrote into our own template would be a check that cannot fail; this reads
  # the object the GAME constructed, through the control.
  #
  # A row that WAS called and does not read back is the case the coordinator
  # suspected on 2026-09-04 -- a prefab whose `_blocker@0x88` or
  # `_tooltipSettingsHover@0x98` is null, which makes SetTooltip a silent
  # no-op. That hypothesis is neither assumed nor dismissed here: both fields
  # are read and NAMED, so the next run says outright whether a hover area has
  # to be cloned from the stock row or whether the write simply did not land.
  var i2 = 0
  while i2 < gDlrRowCtrl.len and i2 < DlrMaxRows:
    if gDlrTipWant[i2] != nil:
      if nuTooltipTextOf(gDlrRowCtrl[i2]) == gDlrTipWant[i2]:
        gDlrTipVerified = gDlrTipVerified + 1
      else:
        let hov = (if nuOk(gDlrRowCtrl[i2], DlrOffScTooltipHover + 8'i32):
                     cNuGetRef(gDlrRowCtrl[i2], DlrOffScTooltipHover) else: nil)
        let blk = (if nuOk(gDlrRowCtrl[i2], DlrOffScBlocker + 8'i32):
                     cNuGetRef(gDlrRowCtrl[i2], DlrOffScBlocker) else: nil)
        warn "dlss rows: tooltip '" & gDlrRowKey[i2] & "' -- SetTooltip was " &
             "CALLED and the finished state does NOT carry our string. On " &
             "this row _tooltipSettingsHover@0x98 = " &
             (if hov == nil: "NULL" else: "0x" & hexOf(cast[uint64](hov))) &
             " and _blocker@0x88 = " &
             (if blk == nil: "NULL" else: "0x" & hexOf(cast[uint64](blk))) &
             ". A NULL blocker is SetTooltip's FIRST no-op path and means " &
             "this prefab needs a SettingsHoverTooltipArea cloned from the " &
             "stock '" & DlrAnchorName & "' row before any tooltip can " &
             "attach; a non-null blocker with a null hover area means " &
             "TryGetTooltip answered false. Either way this row shows NO " &
             "tooltip and is not counted as a pass."
    i2 = i2 + 1

## ---------------------------------------------------------------------------
## THE DROPDOWN LABEL -- what "Blank item" actually was
##
## OBSERVED on the deployed build 61238a816f58 (the player, looking at the
## Graphics page): the two DLSS choice rows read "Blank item". OBSERVED in the
## host log for the same boot: "DROPDOWNS -- 2 of 2 ... filled by CALLING the
## game's own Show" and "5 of 5 show the player's CONFIG value". Both log lines
## were true and neither was about the label.
##
## MEASURED, and this is the whole diagnosis: `set_CurrentIndex` @0x698560 is
## `mov [rcx+0xE8], edx ; ret` (`disasm 0x698560`). It stores the index and
## refreshes nothing. The game itself never calls it alone -- `UpdateValue`
## @0x16AEAC0 writes the same field and then tail-dispatches through
## `[klass+0x308]/[klass+0x310]` with `_values[i]`'s string (`disasm 0x16aeac0
## --len 470`, +0x121 onward). `BaseDropDownBox::SetLabelText` @0x16AEE60 is
## seventeen bytes performing exactly that dispatch (`disasm 0x16aee60`). So
## the box was correctly SELECTED and never TOLD to redraw, and "Blank item" is
## the caption the cloned prefab was authored with.
##
## THE INDEX IS READ BACK FROM THE CONTROL, NOT REMEMBERED. Which choice a row
## ends on is decided inside `sbdRegisterDropdown` from the player's config,
## clamped to the choice count, and this file does not see that number. Asking
## `get_CurrentIndex` @0x698550 -- a DIFFERENT function from the one that
## wrote it -- is both the only way to know and the only way this stays correct
## if the seed changes.
##
## THE VERDICT IS THE TMP, NOT THE CALL. `nuDropDownSetLabel` returning true
## means a call was made. What the player reads is
## `DropDownBox._currentValueText@0xf0`, which the game's own `SetTextInternal`
## writes (`disasm 0x16b0c40`), so reading THAT back and comparing it to the
## caption is a property of the finished state. Its being null is a THIRD
## outcome -- a `DropDownBoxNewStyle` has no such field -- and is counted apart.
proc dlrApplyDropdownLabels() =
  ## Refresh the visible caption of every dropdown row we built, then judge by
  ## reading the label TMP. Runs ONCE per build, off any per-frame path, and
  ## allocates only the interned caption strings, which the intern table holds
  ## for the session.
  if gDlrRowDdb.len == 0: return
  var i = 0
  while i < gDlrRowDdb.len and i < DlrMaxRows:
    let ddb = gDlrRowDdb[i]
    if ddb == nil:
      i = i + 1
      continue
    gDlrLblAsked = gDlrLblAsked + 1
    let (readable, idx) = nuDropDownIndex(ddb)
    if not readable:
      gDlrLblInconclusive = gDlrLblInconclusive + 1
      if gDlrLblWhy.len == 0:
        gDlrLblWhy = "'" & gDlrRowKey[i] & "': get_CurrentIndex @0x698550 " &
                     "did not answer, so there is no chosen value to name " &
                     "and NOTHING was written to the label"
      i = i + 1
      continue
    let choices = gDlrRowChoices[i]
    if idx < 0'i32 or int(idx) >= choices.len:
      gDlrLblInconclusive = gDlrLblInconclusive + 1
      if gDlrLblWhy.len == 0:
        gDlrLblWhy = "'" & gDlrRowKey[i] & "': the box reports index " & $idx &
                     " and this row declares " & $choices.len & " choice(s), " &
                     "so the caption for that index is not knowable here. " &
                     "NOTHING was written -- inventing a string would put a " &
                     "caption on screen that names no real value"
      i = i + 1
      continue
    let want = choices[int(idx)]
    var w = ""
    if not nuDropDownSetLabel(ddb, want, w):
      if gDlrLblWhy.len == 0:
        gDlrLblWhy = "'" & gDlrRowKey[i] & "': " & w
      i = i + 1
      continue
    gDlrLblCalled = gDlrLblCalled + 1
    # THE READBACK. A different object from anything written above: the TMP the
    # game's own SetTextInternal drives.
    let tmp = nuDropDownLabelTmp(ddb)
    if tmp == nil:
      gDlrLblInconclusive = gDlrLblInconclusive + 1
      if gDlrLblWhy.len == 0:
        gDlrLblWhy = "'" & gDlrRowKey[i] & "': SetLabelText was CALLED and " &
                     "_currentValueText@0xf0 read null, so the label could " &
                     "not be examined. That field is declared by DropDownBox " &
                     "and not by DropDownBoxNewStyle, so this is most likely " &
                     "'this clone is a NewStyle box', which is INCONCLUSIVE " &
                     "and not a failure"
      i = i + 1
      continue
    let got = nuGetText(tmp)
    if got == want:
      gDlrLblVerified = gDlrLblVerified + 1
    else:
      warn "dlss rows: LABEL '" & gDlrRowKey[i] & "' -- SetLabelText " &
           "@0x16AEE60 was called with '" & want & "' (index " & $idx &
           ") and the box's own _currentValueText@0xf0 now reads '" & got &
           "'. The player sees that second string, not the first."
      if gDlrLblWhy.len == 0:
        gDlrLblWhy = "'" & gDlrRowKey[i] & "': the label reads '" & got &
                     "' after the call, not '" & want & "'"
    i = i + 1

proc dlrBuild(): bool =
  ## Build the five rows into the live Graphics panel. Called ONCE, from the
  ## tick, only after that panel has actually been observed up.
  result = false
  if gDlrBuilt or gDlrOff or not gDlrOn: return
  inc gDlrTried
  if not nuTargetsBindOk():
    dlrNoteFault("the aowl_nu_targets POSITIONAL self-check FAILED, so every " &
                 "call this file makes would go to the wrong method with the " &
                 "wrong frame. Nothing was built.")
    return
  let tab = dlrTab()
  if tab == nil:
    dlrNoteFault("the GraphicsSettingsTab component could not be reached by " &
                 "walking from the live 'Graphics Settings' panel transform. " &
                 "Without it there is no row parent and no prefab, so nothing " &
                 "was built.")
    return
  let parent = (if nuOk(tab, DlrOffGfxContainer + 8'i32):
                  cNuGetRef(tab, DlrOffGfxContainer) else: nil)
  if not nuOk(parent, 0x10'i32) or not nuAlive(parent):
    dlrNoteFault("GraphicsSettingsTab._settingsContainer @0x98 read null, " &
                 "unreadable or not a live Unity object. That field is " &
                 "serialized and is populated when the prefab loads, so this " &
                 "is 'asked too early' rather than a wrong offset. Nothing " &
                 "was built and nothing was parented anywhere.")
    return
  let togPrefab = (if nuOk(tab, DlrOffToggleTmpl + 8'i32):
                     cNuGetRef(tab, DlrOffToggleTmpl) else: nil)
  # `GraphicsSettingsTab._dropDownTemplate` @0xB0 -- MEASURED
  # (`tools/fldoff.py field EFT.UI.Settings.GraphicsSettingsTab
  # _dropDownTemplate`), and NULL-CAPABLE like every other serialized template
  # here. Fetched unconditionally so the census can say "the flag was on and
  # the prefab was missing", which is not the same as "the flag was off".
  let ddPrefab = (if nuOk(tab, DlrOffDropDownTmpl + 8'i32):
                    cNuGetRef(tab, DlrOffDropDownTmpl) else: nil)
  let sliPrefab = (if nuOk(tab, DlrOffFloatSliderTmpl + 8'i32):
                     cNuGetRef(tab, DlrOffFloatSliderTmpl) else: nil)
  if not nuOk(togPrefab, 0x10'i32) and not nuOk(sliPrefab, 0x10'i32):
    dlrNoteFault("NEITHER _toggleTemplate @0xb8 nor " &
                 "_selectFloatSliderTemplate @0xc8 read back as a live " &
                 "object, so there is no prefab to instantiate. Refusing to " &
                 "fall back to building controls from scratch.")
    return
  let rows = dlrCatalogue()
  gDlrRowGo = @[]
  gDlrRowKey = @[]
  gDlrRowT = @[]
  gDlrRowCtrl = @[]
  gDlrRowTip = @[]
  gDlrTipWant = @[]
  var built = 0
  var refused = 0
  var seeded = 0
  var i = 0
  while i < rows.len and i < DlrMaxRows:
    let r = rows[i]
    let prefab = (if r.kind == dlrToggle: togPrefab else: sliPrefab)
    if not nuOk(prefab, 0x10'i32):
      refused = refused + 1
      i = i + 1
      continue
    var sl: Il2CppPtr = nil
    var ct: Il2CppPtr = nil
    var dd: Il2CppPtr = nil
    # THE DROPDOWN IS TRIED FIRST AND FALLS BACK, NEVER THE OTHER WAY. A
    # refusal at any of the six proofs inside `nuDropDownShow` leaves the row
    # as the stepper slider that has been shipping -- a working control, not a
    # missing one -- and the census records that it happened and why.
    var wantDrop = (r.kind == dlrDropdown and gDlrDropOn and
                    nuOk(ddPrefab, 0x10'i32))
    if r.kind == dlrDropdown and gDlrDropOn:
      gDlrDropWanted = gDlrDropWanted + 1
      if not wantDrop and gDlrDropWhy.len == 0:
        gDlrDropWhy = "GraphicsSettingsTab._dropDownTemplate @0xB0 did not " &
                      "read back as a live object, so there is no dropdown " &
                      "prefab to clone"
    var go: Il2CppPtr = nil
    if wantDrop:
      go = dlrMakeRow(ddPrefab, parent, r, true, sl, ct, dd)
      if go == nil:
        wantDrop = false
    if go == nil:
      go = dlrMakeRow(prefab, parent, r, false, sl, ct, dd)
    if go != nil:
      gDlrRowGo.add go
      gDlrRowKey.add r.key
      # The row's TRANSFORM, captured HERE rather than re-found by name later:
      # a second lookup could bind a different object and the placement
      # readback would then be true of something that is not our row.
      gDlrRowT.add nuTransformOf(go)
      gDlrRowCtrl.add ct
      gDlrRowTip.add r.tip
      gDlrTipWant.add nil
      # The DropDownBox this row ended up with (nil for a slider or a toggle,
      # and nil for a choice row that FELL BACK to the stepper), plus the
      # captions it declares. Captured HERE, from the pointers this loop
      # already holds, so the label pass cannot bind a different object.
      gDlrRowDdb.add (if wantDrop: dd else: nil)
      gDlrRowChoices.add r.choices
      built = built + 1
      # THE VALUE BINDING (settingsbind.nim, flag `settingsRowsBind`, default
      # OFF -- with it off both calls do nothing and the row is a real control
      # that changes nothing). The pointers handed over are the ones this loop
      # ALREADY HOLDS; nothing is re-found by name or by index later.
      if wantDrop and dd != nil:
        gDlrDropBuilt = gDlrDropBuilt + 1
        if sbdRegisterDropdown(DlrGuid, r.key, dd,
                               int32(r.choices.len), int32(r.def + 0.5'f32)):
          seeded = seeded + 1
      elif r.kind == dlrToggle:
        if sbdRegisterToggle(DlrGuid, r.key, ct, r.defB):
          seeded = seeded + 1
      elif sl != nil:
        if sbdRegisterSlider(DlrGuid, r.key, sl, r.lo, r.hi, r.def):
          seeded = seeded + 1
    else:
      refused = refused + 1
    i = i + 1
  if built == 0:
    dlrNoteFault("zero rows were built out of " & $rows.len & " declared (" &
                 $refused & " refused). Nothing is left in the Graphics page.")
    discard dlrDestroyAll()
    return
  gDlrBuilt = true
  gDlrBuiltN = built
  gDlrSeeded = seeded
  gDlrRefused = refused
  dlrPlaceRows(parent)
  # AFTER the seed, because the caption must name whichever value the seed
  # chose, and the seed happens inside sbdRegisterDropdown in the loop above.
  dlrApplyDropdownLabels()
  dlrApplyTooltips(parent)
  result = true

