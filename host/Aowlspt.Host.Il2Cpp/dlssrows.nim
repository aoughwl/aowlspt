    else:
      warn "dlss rows: TOOLTIPS -- " & $gDlrTipAsked & " asked, " &
           $gDlrTipCalled & " call(s) made, and only " & $gDlrTipVerified &
           " READ BACK as the string handed over. SetTooltip has three silent " &
